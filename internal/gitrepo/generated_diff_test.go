func TestGeneratedDiffHeuristics(t *testing.T) {
	for _, test := range []struct {
		name string
		text string
		want bool
	}{
		{name: "nested/package-lock.json", want: true},
		{name: "nested/Cargo.lock", want: true},
		{name: "yarn.lock", want: true},
		{name: "bun.lock", want: true},
		{name: "go.sum", want: true},
		{name: "dist/app.MIN.mjs", want: true},
		{name: "dist/styles.min.css", want: true},
		{name: "dist/bundle.js", text: strings.Repeat("x=0;", 80), want: true},
		{name: "dist/bundle.cjs", text: strings.Repeat("x=0;", 80), want: true},
		{name: "schema.go", text: "// Code generated by protoc. DO NOT EDIT.\npackage schema\n", want: true},
		{name: "schema.ts", text: "\uFEFF/*\n * This file was automatically generated by OpenAPI Generator.\n */\n", want: true},
		{name: "schema.py", text: "# @generated\nprint('schema')\n", want: true},
		{name: "styles.css", text: "body {\n  color: white;\n}\n"},
		{name: "notes.txt", text: "This file was generated by a tool I wrote."},
		{name: "schema.ts", text: strings.Repeat("\n", 40) + "// This file was automatically generated.\n"},
		{name: "vendor/example.com/manual.txt", text: "Written by hand.\n"},
		{name: "service.lock", text: "1234\n"},
	} {
		t.Run(test.name, func(t *testing.T) {
			got := generatedDiffHeuristic(&FileContent{Path: test.name, Text: test.text})
			if got != test.want {
				t.Fatalf("generated = %t, want %t", got, test.want)
			}
		})
	}
}

func TestGeneratedDiffSelectsAttributesWithOneGitCall(t *testing.T) {
	repo, dir := fixture(t)
	write(t, dir, ".gitattributes", "yarn.lock linguist-generated\neditor.min.js -linguist-generated\n")
	git(t, dir, "add", ".gitattributes")
	write(t, dir, ".gitattributes", "yarn.lock linguist-generated=false\n\"-plain text.txt\" linguist-generated=true\n")
	ctx := context.Background()
	reset, calls := gitCallLog(t)
	for _, test := range []struct {
		name, revision string
		want           bool
	}{
		{name: "yarn.lock", revision: "INDEX", want: true},
		{name: "yarn.lock", revision: "WORKTREE"},
		{name: "editor.min.js", revision: "INDEX"},
		{name: "-plain text.txt", revision: "WORKTREE", want: true},
		{name: "normal.txt", revision: "WORKTREE"},
		{name: "bun.lock", revision: "WORKTREE", want: true},
	} {
		reset()
		diff := Diff{Text: "patch", New: &FileContent{Path: test.name, Revision: test.revision, Present: true}}
		if got := repo.isGeneratedDiff(ctx, diff); got != test.want {
			t.Errorf("%s %s generated = %t, want %t", test.revision, test.name, got, test.want)
		}
		if got := calls("check-attr"); got != 1 {
			t.Errorf("%s %s attribute calls = %d, want 1", test.revision, test.name, got)
		}
		if calls("ls-tree")+calls("cat-file")+calls("ls-files") != 0 {
			t.Errorf("%s %s re-read file contents", test.revision, test.name)
		}
	}
	reset()
	for _, diff := range []Diff{
		{Text: "multi-file diff"},
		{Text: "binary", Binary: true, New: &FileContent{Path: "yarn.lock", Revision: "WORKTREE", Present: true}},
		{Text: "link", New: &FileContent{Path: "yarn.lock", Revision: "WORKTREE", Present: true, Unsupported: true}},
		{New: &FileContent{Path: "yarn.lock", Revision: "WORKTREE", Present: true}},
	} {
		if repo.isGeneratedDiff(ctx, diff) {
			t.Errorf("unexpected generated diff: %+v", diff)
		}
	}
	if got := calls("check-attr"); got != 0 {
		t.Errorf("unsupported previews started %d attribute calls", got)
	}
}

func TestGeneratedDiffUsesHistoricalAttributeTree(t *testing.T) {
	repo, dir := fixture(t)
	write(t, dir, "pkg/.gitattributes", "yarn.lock -linguist-generated\nplain.txt linguist-generated\n")
	write(t, dir, "pkg/yarn.lock", "lock contents\n")
	write(t, dir, "pkg/plain.txt", "plain contents\n")
	write(t, dir, "pkg/local.txt", "local contents\n")
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-m", "historical attributes")
	before := git(t, dir, "rev-parse", "HEAD")
	git(t, dir, "rm", "pkg/.gitattributes", "pkg/yarn.lock")
	git(t, dir, "commit", "-m", "remove attributes and lockfile")
	after := git(t, dir, "rev-parse", "HEAD")
	write(t, dir, "pkg/.gitattributes", "yarn.lock linguist-generated\nplain.txt -linguist-generated\nlocal.txt linguist-generated\n")
	git(t, dir, "add", "pkg/.gitattributes")
	ctx := context.Background()
	if _, err := repo.git(ctx, "check-attr", "--source", before+"^{tree}", generatedDiffAttribute, "--", "pkg/plain.txt"); err != nil {
		if generatedDiffSourceUnsupported(err) {
			t.Skip("Git does not support check-attr --source")
		}
		t.Fatal(err)
	}

	plainBefore := &FileContent{Path: "pkg/plain.txt", Revision: before, Present: true}
	localAfter := &FileContent{Path: "pkg/local.txt", Revision: after, Present: true}
	localHead := &FileContent{Path: "pkg/local.txt", Revision: "HEAD", Present: true}
	lockBefore := &FileContent{Path: "pkg/yarn.lock", Revision: before, Present: true}
	lockDeleted := &FileContent{Path: "pkg/yarn.lock", Revision: after}
	for _, test := range []struct {
		name     string
		old, new *FileContent
		want     bool
	}{
		{name: "historical explicit true", new: plainBefore, want: true},
		{name: "historical explicit false", new: lockBefore},
		{name: "deleted file uses old-side false", old: lockBefore, new: lockDeleted},
		{name: "no fallback to current rules after historical removal", new: localAfter},
		{name: "staged deletion uses HEAD attributes", old: localHead},
		{name: "rename uses new-side rule", old: lockBefore, new: plainBefore, want: true},
		{name: "missing tree keeps diff visible", new: &FileContent{
			Path: "pkg/yarn.lock", Revision: strings.Repeat("a", len(before)), Present: true,
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			if got := repo.isGeneratedDiff(ctx, Diff{Text: "patch", Old: test.old, New: test.new}); got != test.want {
				t.Fatalf("generated = %t, want %t", got, test.want)
			}
		})
	}
}

func TestGeneratedDiffFallbackForUnsupportedHistoricalSource(t *testing.T) {
	revision := strings.Repeat("a", 40)
	unsupported := &commandError{code: 129, message: "error: unknown option `source'\r\nusage: git check-attr"}
	missingTree := &commandError{code: 128, message: "fatal: not a valid tree-ish source"}
	otherOption := &commandError{code: 129, message: "error: unknown option `stdin'"}
	for _, test := range []struct {
		name, path, revision, text string
		err                        error
		want                       bool
	}{
		{name: "historical lockfile", path: "pkg/yarn.lock", revision: revision, err: unsupported, want: true},
		{name: "historical generated header", path: "schema.ts", revision: revision,
			text: "// This file was generated by OpenAPI Generator.\n", err: unsupported, want: true},
		{name: "historical handwritten file", path: "normal.txt", revision: revision, err: unsupported},
		{name: "HEAD lockfile", path: "pkg/yarn.lock", revision: "HEAD", err: unsupported, want: true},
		{name: "worktree error", path: "pkg/yarn.lock", revision: "WORKTREE", err: unsupported},
		{name: "index error", path: "pkg/yarn.lock", revision: "INDEX", err: unsupported},
		{name: "missing tree", path: "pkg/yarn.lock", revision: revision, err: missingTree},
		{name: "different unknown option", path: "pkg/yarn.lock", revision: revision, err: otherOption},
		{name: "cancelled", path: "pkg/yarn.lock", revision: revision, err: context.Canceled},
	} {
		t.Run(test.name, func(t *testing.T) {
			source := &FileContent{Path: test.path, Revision: test.revision, Text: test.text, Present: true}
			if got := generatedDiffFromAttributes(source, "", test.err); got != test.want {
				t.Fatalf("generated = %t, want %t", got, test.want)
			}
		})
	}
}
