package gitrepo

import (
	"context"
	"path"
	"regexp"
	"strings"
	"time"

	"github.com/go-enry/go-enry/v2"
)

const generatedDiffAttribute = "linguist-generated"

var generatedDiffHeader = regexp.MustCompile(
	`(?i)^[ \t]*(?://+|/\*+|\*+|#+|<!--|--)[ \t]*` +
		`(?:<auto-generated\b|@generated\b|code generated by\b|` +
		`(?:this (?:file|code) (?:is|was) )?(?:automatically generated\b|auto[- ]?generated\b|generated (?:by|from|using)\b)|` +
		`this (?:file|code) (?:is|was) generated[.!]?[ \t]+do not (?:edit|modify)\b)`,
)

// isGeneratedDiff 仅分类所选文件的差异。删除使用旧版本，其余使用新版本。
// ^{tree} 强制 Git 解析历史属性树，避免缺失的完整对象 ID 被当成未指定属性。
// 独立传入 --source，以便精确识别旧 Git 报告的未知选项。
func (repo *Repository) isGeneratedDiff(ctx context.Context, diff Diff) bool {
	source := diff.New
	if source == nil || !source.Present {
		source = diff.Old
	}
	if diff.Text == "" || diff.Binary || source == nil || !source.Present ||
		source.Binary || source.Unsupported || validPath(source.Path) != nil {
		return false
	}
	args := []string{"check-attr", "-z"}
	switch source.Revision {
	case "WORKTREE":
	case "INDEX":
		args = append(args, "--cached")
	default:
		if source.Revision != "HEAD" && validCommitHash(source.Revision) != nil {
			return false
		}
		args = append(args, "--source", source.Revision+"^{tree}")
	}
	args = append(args, generatedDiffAttribute, "--", source.Path)
	output, limited, err := runCapped(ctx, repo.Path, "", 3*time.Second, 16<<10, args...)
	if limited {
		return false
	}
	return generatedDiffFromAttributes(source, output, err)
}

func generatedDiffFromAttributes(source *FileContent, output string, err error) bool {
	if err != nil {
		return source.Revision != "WORKTREE" && source.Revision != "INDEX" &&
			generatedDiffSourceUnsupported(err) && generatedDiffHeuristic(source)
	}
	value, ok := strings.CutPrefix(output, source.Path+"\x00"+generatedDiffAttribute+"\x00")
	if !ok {
		return false
	}
	value, ok = strings.CutSuffix(value, "\x00")
	if !ok || strings.ContainsRune(value, 0) {
		return false
	}
	switch strings.ToLower(value) {
	case "unset", "false":
		return false
	case "set", "true":
		return true
	default:
		return generatedDiffHeuristic(source)
	}
}

func generatedDiffSourceUnsupported(err error) bool {
	if !exitCode(err, 129) {
		return false
	}
	line, _, _ := strings.Cut(err.Error(), "\n")
	return strings.TrimSuffix(line, "\r") == "error: unknown option `source'"
}

func generatedDiffHeuristic(source *FileContent) bool {
	name := path.Base(source.Path)
	lower := strings.ToLower(name)
	switch lower {
	case "bun.lock", "gemfile.lock", "go.sum", "go.work.sum", "gradle.lockfile", "mix.lock",
		"package.resolved", "packages.lock.json", "pnpm-lock.yml", "podfile.lock", "pubspec.lock", "yarn.lock":
		return true
	}
	ext := path.Ext(lower)
	switch ext {
	case ".css", ".js", ".mjs", ".cjs":
		if strings.HasSuffix(strings.TrimSuffix(lower, ext), ".min") {
			return true
		}
	}
	if ext == ".mjs" || ext == ".cjs" {
		name = strings.TrimSuffix(name, path.Ext(name)) + ".js"
	}
	sample := strings.TrimPrefix(source.Text, "\uFEFF")
	sample = sample[:min(len(sample), languageSample)]
	lines := 0
	for line := range strings.SplitSeq(sample, "\n") {
		if lines == 40 {
			break
		}
		if generatedDiffHeader.MatchString(line) {
			return true
		}
		lines++
	}
	return enry.IsGenerated(name, []byte(sample))
}
