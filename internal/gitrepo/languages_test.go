func TestRepositoryLanguagesUseCommittedSourceBytes(t *testing.T) {
	repo, path := fixture(t)
	goSource := "package main\n\nfunc main() {}\n"
	script := "#!/usr/bin/env python3\nprint('hello')\n"
	write(t, path, "源码/main.go", goSource)
	write(t, path, "test/helper_test.go", goSource)
	write(t, path, "tools/run", script)
	write(t, path, "vendor/large.js", strings.Repeat("var dependency = 1;\n", 100))
	write(t, path, "node_modules/library/index.js", strings.Repeat("var dependency = 1;\n", 100))
	write(t, path, "generated.go", "// Code generated by test. DO NOT EDIT.\n"+strings.Repeat(goSource, 100))
	write(t, path, "README.md", strings.Repeat("Documentation\n", 100))
	write(t, path, "settings.json", strings.Repeat(" ", 1000)+"{}\n")
	write(t, path, "binary.go", "package main\n\x00"+strings.Repeat("binary", 100))
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "language fixtures")
	tree, err := repo.LanguageTree(context.Background())
	if err != nil || tree == "" {
		t.Fatalf("tree = %q, %v", tree, err)
	}
	write(t, path, "源码/main.go", strings.Repeat("changed", 1000))
	write(t, path, "untracked.swift", strings.Repeat("print(1)\n", 1000))
	git(t, path, "add", "源码/main.go")
	summary, err := repo.Languages(context.Background(), tree)
	if err != nil {
		t.Fatal(err)
	}
	if !summary.Complete || summary.Tree != tree || len(summary.Languages) != 2 {
		t.Fatalf("summary = %+v", summary)
	}
	if got := summary.Languages[0]; got.Name != "Go" || got.Bytes != int64(2*len(goSource)) || got.Color != "#00ADD8" {
		t.Fatalf("Go source bytes = %+v", got)
	}
	if got := summary.Languages[1]; got.Name != "Python" || got.Bytes != int64(len(script)) {
		t.Fatalf("extensionless script = %+v", got)
	}
}

func TestRepositoryLanguagesTreeChangesOnlyWithContent(t *testing.T) {
	repo, path := fixture(t)
	ctx := context.Background()
	tree, err := repo.LanguageTree(ctx)
	if err != nil || tree != "" {
		t.Fatalf("unborn tree = %q, %v", tree, err)
	}
	write(t, path, "main.go", "package main\n")
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "Go")
	first, err := repo.LanguageTree(ctx)
	if err != nil {
		t.Fatal(err)
	}
	git(t, path, "commit", "--allow-empty", "-m", "same content")
	same, err := repo.LanguageTree(ctx)
	if err != nil || same != first {
		t.Fatalf("empty commit invalidates content cache: %q != %q, %v", same, first, err)
	}
	git(t, path, "switch", "-c", "python")
	git(t, path, "rm", "main.go")
	write(t, path, "main.py", "print('hello')\n")
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "Python")
	second, err := repo.LanguageTree(ctx)
	if err != nil || second == first {
		t.Fatalf("changed content keeps old cache: %q, %v", second, err)
	}
	old, err := repo.Languages(ctx, first)
	if err != nil || len(old.Languages) != 1 || old.Languages[0].Name != "Go" {
		t.Fatalf("analysis did not pin its tree: %+v, %v", old, err)
	}
	current, err := repo.Languages(ctx, second)
	if err != nil || len(current.Languages) != 1 || current.Languages[0].Name != "Python" {
		t.Fatalf("new tree = %+v, %v", current, err)
	}
}

func TestRepositoryLanguagesExcludeLinksSubmodulesAndOversizedFiles(t *testing.T) {
	repo, path := fixture(t)
	write(t, path, "main.go", "package main\n")
	write(t, path, "large.py", strings.Repeat("print(1)\n", 150000))
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "source")
	head := git(t, path, "rev-parse", "HEAD")
	blob := git(t, path, "hash-object", "main.go")
	git(t, path, "update-index", "--add", "--cacheinfo", "120000,"+blob+",linked.swift")
	git(t, path, "update-index", "--add", "--cacheinfo", "160000,"+head+",submodule")
	git(t, path, "commit", "-m", "links")
	tree, err := repo.LanguageTree(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	summary, err := repo.Languages(context.Background(), tree)
	if err != nil || summary.Complete || len(summary.Languages) != 1 || summary.Languages[0].Name != "Go" {
		t.Fatalf("bounded analysis = %+v, %v", summary, err)
	}
}

func TestRepositoryLanguagesEmptyTieAndCancellation(t *testing.T) {
	repo, path := fixture(t)
	ctx := context.Background()
	git(t, path, "commit", "--allow-empty", "-m", "empty")
	tree, err := repo.LanguageTree(ctx)
	if err != nil {
		t.Fatal(err)
	}
	empty, err := repo.Languages(ctx, tree)
	if err != nil || !empty.Complete || len(empty.Languages) != 0 {
		t.Fatalf("empty tree = %+v, %v", empty, err)
	}
	write(t, path, "main.go", "package main\n")
	write(t, path, "main.py", "print('hi') \n")
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "tie")
	tree, err = repo.LanguageTree(ctx)
	if err != nil {
		t.Fatal(err)
	}
	first, err := repo.Languages(ctx, tree)
	if err != nil {
		t.Fatal(err)
	}
	second, err := repo.Languages(ctx, tree)
	if err != nil || !reflect.DeepEqual(first, second) || len(first.Languages) != 2 ||
		first.Languages[0].Name != "Go" || first.Languages[0].Bytes != first.Languages[1].Bytes {
		t.Fatalf("stable tie = %+v, %+v, %v", first, second, err)
	}
	cancelled, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := repo.Languages(cancelled, tree); !errors.Is(err, context.Canceled) {
		t.Fatalf("cancelled analysis = %v", err)
	}
	for _, invalid := range []string{"HEAD", "--all", strings.Repeat("x", 40)} {
		if _, err := repo.Languages(ctx, invalid); err == nil {
			t.Fatalf("accepted invalid tree %q", invalid)
		}
	}
}

func TestLanguageBatchAcceptsFragmentedObjects(t *testing.T) {
	goSource := "package main\n" + strings.Repeat("// source\n", 8000)
	python := "#!/usr/bin/python3\nprint('ok')\n"
	writer := &languageBatchWriter{
		ctx: context.Background(),
		blobs: []languageBlob{
			{path: "中文\nsource.go", object: strings.Repeat("a", 40), size: int64(len(goSource))},
			{path: "run", object: strings.Repeat("b", 40), size: int64(len(python))},
		},
		totals: map[string]int64{},
	}
	input := fmt.Sprintf("%s blob %d\n%s\n%s blob %d\n%s\n",
		strings.Repeat("a", 40), len(goSource), goSource, strings.Repeat("b", 40), len(python), python)
	for offset := 0; offset < len(input); offset += 7 {
		part := input[offset:min(offset+7, len(input))]
		if written, err := writer.Write([]byte(part)); err != nil || written != len(part) {
			t.Fatalf("fragment at %d: written=%d, %v", offset, written, err)
		}
		if len(writer.sample) > 64<<10 {
			t.Fatal("blob sample exceeded memory budget")
		}
	}
	if writer.index != 2 || writer.body || writer.totals["Go"] != int64(len(goSource)) ||
		writer.totals["Python"] != int64(len(python)) {
		t.Fatalf("fragmented batch = %+v", writer)
	}
}

func TestRepositoryLanguageReadBudgetDoesNotClaimCompleteStatistics(t *testing.T) {
	repo, path := fixture(t)
	source := "package main\n" + strings.Repeat(" ", (1<<20)-len("package main\n"))
	for index := 0; index < 33; index++ {
		write(t, path, fmt.Sprintf("source%02d.go", index), source)
	}
	git(t, path, "add", ".")
	git(t, path, "commit", "-m", "read budget")
	tree, err := repo.LanguageTree(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	summary, err := repo.Languages(context.Background(), tree)
	if err != nil || summary.Complete || len(summary.Languages) != 1 || summary.Languages[0].Bytes != 32<<20 {
		t.Fatalf("budgeted summary = %+v, %v", summary, err)
	}
}

func TestRepositoryLanguagesStreamLargeVendorTree(t *testing.T) {
	repo, path := fixture(t)
	write(t, path, "main.go", "package main\n")
	blob := git(t, path, "hash-object", "-w", "main.go")
	var entries strings.Builder
	for index := 0; index < 18000; index++ {
		fmt.Fprintf(&entries, "100644 blob %s\t%s%05d.go\x00", blob, strings.Repeat("long", 45), index)
	}
	vendor, err := run(context.Background(), path, entries.String(), 15*time.Second, "mktree", "-z")
	if err != nil {
		t.Fatal(err)
	}
	root := fmt.Sprintf("100644 blob %s\tmain.go\x00040000 tree %s\tvendor\x00", blob, strings.TrimSpace(vendor))
	tree, err := run(context.Background(), path, root, 15*time.Second, "mktree", "-z")
	if err != nil {
		t.Fatal(err)
	}
	summary, err := repo.Languages(context.Background(), strings.TrimSpace(tree))
	if err != nil || !summary.Complete || len(summary.Languages) != 1 ||
		summary.Languages[0].Name != "Go" || summary.Languages[0].Bytes != 13 {
		t.Fatalf("large excluded tree blocked source statistics: %+v, %v", summary, err)
	}
}
