package app

import (
	"os"
	"testing"

	"github.com/ysicing/51code/locales"

	"github.com/egoist/mygo/ui"
)

func TestGeneratedFileInChangesWorkspace(t *testing.T) {
	app, path, finish := nativeFixture(t)
	const name = "schema.generated.go"
	writeNativeFile(t, path, name, "// Code generated by schema. DO NOT EDIT.\npackage schema\n")
	app.refresh()
	finish()
	app.selectFile(name, false)
	finish()
	tester := ui.NewTester(app.view, 1024, 680)
	for _, dark := range []bool{false, true} {
		tester.SetDark(dark)
		for _, label := range []string{locales.StageFile(), locales.ExpandGeneratedDiff()} {
			item, ok := tester.AccessByRole(ui.RoleButton, label)
			if !ok || item.Offscreen || item.Disabled {
				t.Fatalf("入口不可用 %q: %+v", label, item)
			}
		}
		if directory := os.Getenv("XSOURCETREE_TEST_SCREENSHOTS"); directory != "" {
			name := "generated-diff-light.png"
			if dark {
				name = "generated-diff-dark.png"
			}
			saveNativeScreenshot(t, tester, directory, name)
		}
	}
	if err := tester.Click(locales.ExpandGeneratedDiff()); err != nil {
		t.Fatal(err)
	}
	if _, ok := tester.Find(locales.DiffText()); !ok {
		t.Fatal("展开后缺少文本差异")
	}
	if err := tester.Click(locales.CollapseGeneratedDiff()); err != nil {
		t.Fatal(err)
	}
	if _, ok := tester.Find(locales.DiffText()); ok {
		t.Fatal("折叠后仍然显示文本差异")
	}
	if err := tester.Click(locales.StageFile()); err != nil {
		t.Fatal(err)
	}
	finish()
	if files := nativeGit(t, path, "diff", "--cached", "--name-only"); files != name {
		t.Fatalf("暂存了 %q，预期 %q", files, name)
	}
}
